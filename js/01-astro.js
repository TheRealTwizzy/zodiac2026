var PORDER = ["Mercury","Venus","Earth","Mars","Jupiter","Saturn","Uranus","Neptune","Pluto"];

function meanLon(idx, T){
  var E = ELEM[PORDER[idx]];
  return E[3] + E[9] * T;
}
function pertVal(e, T){
  var ns = e[0], args = e[1], c = e[2];
  var v = c[0] + c[1]*T + c[2]*T*T;
  for (var k = 0; k < args.length; k++){
    var a = args[k], arg = 0;
    for (var j = 0; j < a.length; j++) if (a[j]) arg += a[j] * meanLon(ns[j], T);
    v += c[3 + 2*k] * sind(arg) + c[4 + 2*k] * cosd(arg);
  }
  return v;
}

/* heliocentric ecliptic longitude / latitude / radius, J2000 frame */
function helioLBR(name, T){
  var E = ELEM[name];
  var a = E[0] + E[6]*T, e = E[1] + E[7]*T, I = E[2] + E[8]*T,
      L = E[3] + E[9]*T, pi = E[4] + E[10]*T, om = E[5] + E[11]*T;
  var w = pi - om;
  var M = norm180(L - pi);
  var Ecc = M + (e * R2D) * sind(M);
  for (var k = 0; k < 15; k++){
    var dM = M - (Ecc - (e * R2D) * sind(Ecc));
    var dE = dM / (1 - e * cosd(Ecc));
    Ecc += dE;
    if (Math.abs(dE) < 1e-11) break;
  }
  var xp = a * (cosd(Ecc) - e);
  var yp = a * Math.sqrt(1 - e*e) * sind(Ecc);
  var cw = cosd(w), sw = sind(w), co = cosd(om), so = sind(om),
      ci = cosd(I), si = sind(I);
  var x = (cw*co - sw*so*ci)*xp + (-sw*co - cw*so*ci)*yp;
  var y = (cw*so + sw*co*ci)*xp + (-sw*so + cw*co*ci)*yp;
  var z = (sw*si)*xp + (cw*si)*yp;
  var r = Math.sqrt(x*x + y*y + z*z);
  var lon = norm360(deg(Math.atan2(y, x)));
  var lat = deg(Math.asin(z / r));
  var P = PERT[name];
  if (P){ lon += pertVal(P.l, T); lat += pertVal(P.b, T); r += pertVal(P.r, T); }
  return { lon: norm360(lon), lat: lat, r: r };
}

/* heliocentric rectangular coordinates, J2000 ecliptic frame, in AU */
function helio(name, T){
  var s = helioLBR(name, T);
  var cb = cosd(s.lat);
  return { x: s.r * cb * cosd(s.lon), y: s.r * cb * sind(s.lon), z: s.r * sind(s.lat) };
}

var LIGHT_DAY = 173.144632674; /* AU per day */

/* apparent geocentric ecliptic longitude of a planet, equinox of date */
function planetLongitude(name, T){
  var earth = helio("Earth", T);
  var p = helio(name, T), dx, dy, dz, dist, tau, T2;
  for (var it = 0; it < 3; it++){
    dx = p.x - earth.x; dy = p.y - earth.y; dz = p.z - earth.z;
    dist = Math.sqrt(dx*dx + dy*dy + dz*dz);
    tau = dist / LIGHT_DAY;
    T2 = T - tau / 36525;
    p = helio(name, T2);
  }
  dx = p.x - earth.x; dy = p.y - earth.y; dz = p.z - earth.z;
  var lon = norm360(deg(Math.atan2(dy, dx)));
  var lat = deg(Math.asin(dz / Math.sqrt(dx*dx + dy*dy + dz*dz)));

  /* annual aberration (Ron-Vondrak simplified: use Earth's velocity) */
  var sun = sunLongitude(T);
  var kappa = 20.49552 / 3600;
  var e0 = 0.016708634 - 0.000042037*T;
  var pi0 = 102.93735 + 1.71946*T;
  var dlon = (-kappa * cosd(sun.trueLon - lon)
              + e0 * kappa * cosd(pi0 - lon)) / cosd(lat);
  lon += dlon;

  var nut = nutation(T);
  return { lon: norm360(lon + precessionLon(T) + nut.dpsi), lat: lat, dist: dist };
}

/* ------------------------------------------------------- sidereal / angles */

function gmst(jdUT){
  var T = (jdUT - 2451545.0) / 36525;
  var th = 280.46061837 + 360.98564736629 * (jdUT - 2451545.0)
         + 0.000387933*T*T - T*T*T/38710000;
  return norm360(th);
}

function ascendant(ramc, eps, lat){
  var y = cosd(ramc);
  var x = -(sind(ramc) * cosd(eps) + tand(lat) * sind(eps));
  return norm360(deg(Math.atan2(y, x)));
}
function midheaven(ramc, eps){
  return norm360(deg(Math.atan2(sind(ramc), cosd(ramc) * cosd(eps))));
}

/* ecliptic longitude of the point whose right ascension is ra */
function lonFromRA(ra, eps){
  return norm360(deg(Math.atan2(sind(ra), cosd(ra) * cosd(eps))));
}

/* Placidus intermediate cusps by semi-arc iteration.
   Returns null when the construction fails (near/inside the polar circles). */
function placidus(ramc, eps, lat){
  /* cusp 11 sits 1/3 of a diurnal semi-arc east of the MC,
     cusp 12 sits 2/3 of the way; cusp 3 sits 1/3 of a nocturnal semi-arc
     west of the IC and cusp 2 sits 2/3 of the way.                        */
  var c11 = cuspSemiArc(ramc, eps, lat, 1/3, false);
  var c12 = cuspSemiArc(ramc, eps, lat, 2/3, false);
  var c2  = cuspSemiArc(ramc, eps, lat, 2/3, true);
  var c3  = cuspSemiArc(ramc, eps, lat, 1/3, true);
  if (c11 == null || c12 == null || c2 == null || c3 == null) return null;
  return [c11, c12, c2, c3].map(function(ra){ return lonFromRA(ra, eps); });
}

/* fraction f of the semi-arc, measured east of the MC (diurnal) or of the IC
   (nocturnal, counted backwards).  Returns right ascension. */
function cuspSemiArc(ramc, eps, lat, f, nocturnal){
  var ra = norm360(ramc + (nocturnal ? 180 - f * 90 : f * 90));
  for (var i = 0; i < 100; i++){
    var dec = deg(Math.atan(tand(eps) * sind(ra)));
    var t = tand(lat) * tand(dec);
    if (Math.abs(t) >= 1) return null;
    var ad = deg(Math.asin(t));
    var next = nocturnal
      ? norm360(ramc + 180 - f * (90 - ad))
      : norm360(ramc + f * (90 + ad));
    if (Math.abs(norm180(next - ra)) < 1e-10){ ra = next; break; }
    ra = next;
  }
  return ra;
}

