function moonLongitude(T){
  var Lp = 218.3164477 + 481267.88123421*T - 0.0015786*T*T
         + T*T*T/538841 - T*T*T*T/65194000;
  var D  = 297.8501921 + 445267.1114034*T - 0.0018819*T*T
         + T*T*T/545868 - T*T*T*T/113065000;
  var M  = 357.5291092 + 35999.0502909*T - 0.0001536*T*T + T*T*T/24490000;
  var Mp = 134.9633964 + 477198.8675055*T + 0.0087414*T*T
         + T*T*T/69699 - T*T*T*T/14712000;
  var F  = 93.2720950 + 483202.0175233*T - 0.0036539*T*T
         - T*T*T/3526000 + T*T*T*T/863310000;
  var A1 = 119.75 + 131.849*T;
  var A2 = 53.09 + 479264.290*T;
  var E  = 1 - 0.002516*T - 0.0000074*T*T;

  var sumL = 0;
  for (var i = 0; i < MOON_LON.length; i++){
    var t = MOON_LON[i];
    var arg = t[0]*D + t[1]*M + t[2]*Mp + t[3]*F;
    var f = 1;
    if (Math.abs(t[1]) === 1) f = E;
    else if (Math.abs(t[1]) === 2) f = E * E;
    sumL += t[4] * f * sind(arg);
  }
  sumL += 3958 * sind(A1) + 1962 * sind(Lp - F) + 318 * sind(A2);
  return norm360(Lp + sumL / 1000000);
}

/* apparent geocentric longitude of the Sun, equinox of date.
   Derived from the fitted Earth-Moon-barycentre series (better than the
   classical low-precision solar theory). */
function sunApparent(T){
  var e = helioLBR("Earth", T);
  var lon = norm360(e.lon + 180);
  lon -= (20.4898 / e.r) / 3600;                 /* annual aberration */
  var nut = nutation(T);
  return norm360(lon + precessionLon(T) + nut.dpsi);
}

/* mean and true lunar node, degrees */
function lunarNode(T, trueNode){
  var Om = 125.0445479 - 1934.1362891*T + 0.0020754*T*T
         + T*T*T/467441 - T*T*T*T/60616000;
  if (!trueNode) return norm360(Om);
  var D  = 297.8501921 + 445267.1114034*T - 0.0018819*T*T;
  var M  = 357.5291092 + 35999.0502909*T - 0.0001536*T*T;
  var Mp = 134.9633964 + 477198.8675055*T + 0.0087414*T*T;
  var F  = 93.2720950 + 483202.0175233*T - 0.0036539*T*T;
  var c = -1.4979 * sind(2*(D - F))
        - 0.1500 * sind(M)
        - 0.1226 * sind(2*D)
        + 0.1176 * sind(2*F)
        - 0.0801 * sind(2*(Mp - F));
  return norm360(Om + c);
}

