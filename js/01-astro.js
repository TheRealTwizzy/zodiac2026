/* ============================================================================
   ASTRO ENGINE — real geocentric ecliptic longitudes (tropical, of date)
   ----------------------------------------------------------------------------
   Sun ........ Meeus low-precision solar theory + nutation + aberration
   Moon ....... Meeus ch.47, 60-term truncated ELP-2000/82 (~10" longitude)
   Planets .... JPL/Standish Keplerian elements (1800-2050) + light-time +
                annual aberration, precessed to the ecliptic of date
   Angles ..... GMST -> RAMC -> Ascendant / Midheaven
   Houses ..... Whole Sign, Equal, Placidus (semi-arc iteration)
   ==========================================================================*/
