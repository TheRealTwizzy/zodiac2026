var BODIES = ["Sun","Moon","Mercury","Venus","Mars","Jupiter","Saturn",
              "Uranus","Neptune","Pluto"];

/* The years PERT.Pluto was fitted over — see the comment above PERT. Every
   other body stays inside half a degree across the whole 1600-2200 form
   range; Pluto does not, so it is the only one with a window. */
var PLUTO_FROM = 1899, PLUTO_TO = 2050;

/* utcJD: Julian Day in UT.  lat/lon in degrees, east positive. */
function chart(utcJD, lat, lon, opts){
  opts = opts || {};
  var y = jdToDate(utcJD);
  var dT = deltaT(y.year, y.month);
  var jdTT = utcJD + dT / 86400;
  var T = (jdTT - 2451545.0) / 36525;
  var nut = nutation(T);
  var eps = meanObliquity(T) + nut.deps;

  var out = { jdUT: utcJD, jdTT: jdTT, T: T, eps: eps, deltaT: dT, bodies: {} };

  out.bodies.Sun = { lon: sunApparent(T), speed: dailySpeed("Sun", T) };
  out.bodies.Moon = { lon: norm360(moonLongitude(T) + nut.dpsi),
                      speed: dailySpeed("Moon", T) };
  /* Pluto's perturbation series is the one fit here that does not degrade
     gracefully. Its secular terms are degrees, not arcseconds, so outside the
     window it was fitted over the correction runs away: about 0.00° across
     1900-2050, then 580° at 2100 and 4745° at 1600. That does not produce a
     slightly-off Pluto, it produces a confident one in the wrong sign, with a
     fabricated retrograde and every aspect and pattern built on top of it.
     Withhold it instead — the same choice the chart already makes for the
     Ascendant when there is no birth time. */
  out.withheld = [];
  for (var i = 2; i < BODIES.length; i++){
    var n = BODIES[i];
    if (n === "Pluto" && (y.year < PLUTO_FROM || y.year > PLUTO_TO)){
      out.withheld.push(n);
      continue;
    }
    var p = planetLongitude(n, T);
    out.bodies[n] = { lon: p.lon, lat: p.lat, dist: p.dist, speed: dailySpeed(n, T) };
  }
  out.bodies.NorthNode = { lon: lunarNode(T, true), speed: -0.0529 };

  var th = gmst(utcJD) + 0.0000001;
  var lst = norm360(th + nut.dpsi * cosd(eps) + lon);
  out.lst = lst;
  out.ramc = lst;
  out.mc = midheaven(lst, eps);
  out.asc = ascendant(lst, eps, lat);
  out.houses = houseCusps(out.asc, out.mc, lst, eps, lat, opts.houseSystem || "whole");
  out.houseSystem = out.houses.system;
  return out;
}

function dailySpeed(name, T){
  var dt = 0.5 / 36525, a, b;
  if (name === "Sun"){ a = sunApparent(T - dt); b = sunApparent(T + dt); }
  else if (name === "Moon"){ a = moonLongitude(T - dt); b = moonLongitude(T + dt); }
  else { a = planetLongitude(name, T - dt).lon; b = planetLongitude(name, T + dt).lon; }
  return norm180(b - a);
}

function houseCusps(asc, mc, ramc, eps, lat, system){
  var c = [], i;
  if (system === "placidus"){
    var p = placidus(ramc, eps, lat);
    if (p){
      c[0] = asc; c[9] = mc;
      c[10] = p[0]; c[11] = p[1]; c[1] = p[2]; c[2] = p[3];
      c[6] = norm360(c[0] + 180); c[7] = norm360(c[1] + 180);
      c[8] = norm360(c[2] + 180); c[3] = norm360(c[9] + 180);
      c[4] = norm360(c[10] + 180); c[5] = norm360(c[11] + 180);
      return { system: "placidus", cusps: c };
    }
    system = "whole";
  }
  if (system === "equal"){
    for (i = 0; i < 12; i++) c[i] = norm360(asc + i * 30);
    return { system: "equal", cusps: c };
  }
  var start = Math.floor(asc / 30) * 30;
  for (i = 0; i < 12; i++) c[i] = norm360(start + i * 30);
  return { system: "whole", cusps: c };
}

function jdToDate(jd){
  var z = Math.floor(jd + 0.5), f = jd + 0.5 - z, a = z, alpha;
  if (z >= 2299161){ alpha = Math.floor((z - 1867216.25) / 36524.25);
    a = z + 1 + alpha - Math.floor(alpha / 4); }
  var b = a + 1524, cc = Math.floor((b - 122.1) / 365.25),
      d = Math.floor(365.25 * cc), e = Math.floor((b - d) / 30.6001);
  var day = b - d - Math.floor(30.6001 * e) + f;
  var month = e < 14 ? e - 1 : e - 13;
  var year = month > 2 ? cc - 4716 : cc - 4715;
  return { year: year, month: month, day: day };
}

