"use strict";

var D2R = Math.PI / 180, R2D = 180 / Math.PI;
function rad(d){ return d * D2R; }
function deg(r){ return r * R2D; }
function norm360(x){ x = x % 360; return x < 0 ? x + 360 : x; }
function norm180(x){ x = norm360(x); return x > 180 ? x - 360 : x; }
function sind(x){ return Math.sin(rad(x)); }
function cosd(x){ return Math.cos(rad(x)); }
function tand(x){ return Math.tan(rad(x)); }

/* ---------------------------------------------------------------- time --- */

/* Julian Day from a Gregorian calendar date + fractional hours UT */
function julianDay(y, m, d, hours){
  if (m <= 2){ y -= 1; m += 12; }
  var A = Math.floor(y / 100);
  var B = 2 - A + Math.floor(A / 4);
  return Math.floor(365.25 * (y + 4716)) + Math.floor(30.6001 * (m + 1))
       + d + B - 1524.5 + (hours || 0) / 24;
}

/* Approximate TT-UT1 (delta T) in seconds. Espenak & Meeus polynomials. */
function deltaT(y, m){
  var yr = y + (m - 0.5) / 12, t, u;
  if (yr >= 2005 && yr < 2050){ t = yr - 2000; return 62.92 + 0.32217*t + 0.005589*t*t; }
  if (yr >= 1986 && yr < 2005){ t = yr - 2000;
    return 63.86 + 0.3345*t - 0.060374*t*t + 0.0017275*t*t*t
         + 0.000651814*Math.pow(t,4) + 0.00002373599*Math.pow(t,5); }
  if (yr >= 1961 && yr < 1986){ t = yr - 1975;
    return 45.45 + 1.067*t - t*t/260 - t*t*t/718; }
  if (yr >= 1941 && yr < 1961){ t = yr - 1950;
    return 29.07 + 0.407*t - t*t/233 + t*t*t/2547; }
  if (yr >= 1920 && yr < 1941){ t = yr - 1920;
    return 21.20 + 0.84493*t - 0.076100*t*t + 0.0020936*t*t*t; }
  if (yr >= 1900 && yr < 1920){ t = yr - 1900;
    return -2.79 + 1.494119*t - 0.0598939*t*t + 0.0061966*t*t*t - 0.000197*Math.pow(t,4); }
  if (yr >= 1860 && yr < 1900){ t = yr - 1860;
    return 7.62 + 0.5737*t - 0.251754*t*t + 0.01680668*t*t*t
         - 0.0004473624*Math.pow(t,4) + t*t*t*t*t/233174; }
  if (yr >= 2050 && yr < 2150){
    return -20 + 32*Math.pow((yr-1820)/100, 2) - 0.5628*(2150 - yr); }
  u = (yr - 1820) / 100;
  return -20 + 32 * u * u;
}

/* mean obliquity of the ecliptic (IAU 1980), degrees; T in Julian centuries TT */
function meanObliquity(T){
  var s = 21.448 - T*(46.8150 + T*(0.00059 - T*0.001813));
  return 23 + (26 + s/60)/60;
}

/* nutation in longitude (deg) and obliquity (deg) — principal terms */
function nutation(T){
  var D  = 297.85036 + 445267.111480*T - 0.0019142*T*T + T*T*T/189474;
  var M  = 357.52772 + 35999.050340*T - 0.0001603*T*T - T*T*T/300000;
  var Mp = 134.96298 + 477198.867398*T + 0.0086972*T*T + T*T*T/56250;
  var F  = 93.27191 + 483202.017538*T - 0.0036825*T*T + T*T*T/327270;
  var Om = 125.04452 - 1934.136261*T + 0.0020708*T*T + T*T*T/450000;
  var dpsi =
      (-171996 - 174.2*T) * sind(Om)
    + (-13187 - 1.6*T) * sind(-2*D + 2*F + 2*Om)
    + (-2274 - 0.2*T) * sind(2*F + 2*Om)
    + (2062 + 0.2*T) * sind(2*Om)
    + (1426 - 3.4*T) * sind(M)
    + (712 + 0.1*T) * sind(Mp)
    + (-517 + 1.2*T) * sind(-2*D + M + 2*F + 2*Om)
    + (-386 - 0.4*T) * sind(2*F + Om)
    + (-301) * sind(Mp + 2*F + 2*Om)
    + (217 - 0.5*T) * sind(-2*D - M + 2*F + 2*Om)
    + (-158) * sind(-2*D + Mp)
    + (129 + 0.1*T) * sind(-2*D + 2*F + Om)
    + (123) * sind(-Mp + 2*F + 2*Om)
    + (63) * sind(2*D)
    + (63 + 0.1*T) * sind(Mp + Om)
    + (-59) * sind(2*D - Mp + 2*F + 2*Om)
    + (-58 - 0.1*T) * sind(-Mp + Om)
    + (-51) * sind(Mp + 2*F + Om)
    + (48) * sind(-2*D + 2*Mp)
    + (46) * sind(-2*Mp + 2*F + Om)
    + (-38) * sind(2*D + 2*F + 2*Om)
    + (-31) * sind(2*Mp + 2*F + 2*Om)
    + (29) * sind(2*Mp)
    + (29) * sind(-2*D + Mp + 2*F + 2*Om)
    + (26) * sind(2*F)
    + (-22) * sind(-2*D + 2*F)
    + (21) * sind(-Mp + 2*F + Om);
  var deps =
      (92025 + 8.9*T) * cosd(Om)
    + (5736 - 3.1*T) * cosd(-2*D + 2*F + 2*Om)
    + (977 - 0.5*T) * cosd(2*F + 2*Om)
    + (-895 + 0.5*T) * cosd(2*Om)
    + (54 - 0.1*T) * cosd(M)
    + (-7) * cosd(Mp)
    + (224 - 0.6*T) * cosd(-2*D + M + 2*F + 2*Om)
    + (200) * cosd(2*F + Om)
    + (129 - 0.1*T) * cosd(Mp + 2*F + 2*Om)
    + (-95 + 0.3*T) * cosd(-2*D - M + 2*F + 2*Om);
  return { dpsi: dpsi / 36000000, deps: deps / 36000000 };
}

/* accumulated general precession in longitude since J2000, degrees */
function precessionLon(T){
  return (5028.796195 * T + 1.1054348 * T * T) / 3600;
}

/* ----------------------------------------------------------------- sun --- */

function sunLongitude(T){
  var L0 = 280.46646 + 36000.76983*T + 0.0003032*T*T;
  var M  = 357.52911 + 35999.05029*T - 0.0001537*T*T;
  var e  = 0.016708634 - 0.000042037*T - 0.0000001267*T*T;
  var C  = (1.914602 - 0.004817*T - 0.000014*T*T) * sind(M)
         + (0.019993 - 0.000101*T) * sind(2*M)
         + 0.000289 * sind(3*M);
  var trueLon = L0 + C;
  var v = M + C;
  var R = (1.000001018 * (1 - e*e)) / (1 + e * cosd(v));
  var Om = 125.04 - 1934.136*T;
  var apparent = trueLon - 0.00569 - 0.00478 * sind(Om); /* aberration + nut. */
  return { lon: norm360(apparent), R: R, trueLon: norm360(trueLon) };
}

